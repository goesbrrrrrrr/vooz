# Расположение узлов — второй по важности фактор после гладкости функции.
# В остаточном члене интерполирования
#
#     R_n(f,x) = f^(n+1)(ksi)/(n+1)! * (x-x_0)(x-x_1)...(x-x_n)
#
# первый сомножитель зависит только от функции и никак нам не подчиняется,
# а второй, omega(x) = PROD (x - x_i), определяется выбором узлов. Влиять
# можно только на него — минимизировать его максимум на отрезке.
# =============================================================================
def nodes_uniform(a, b, n):
    """
    Равномерное разбиение: x_i = a + (b-a)/n * i,  i = 0..n.

    Плата за простоту: max|omega(x)| достигается вблизи концов отрезка и
    растёт с n очень быстро. Отсюда выбросы погрешности у краёв — явление
    Рунге.
    """
    return [a + (b - a) * i / n for i in range(n + 1)]


def nodes_chebyshev(a, b, n):
    """
    Разбиение Чебышева: нули многочлена Чебышева 1-го рода T_{n+1},
    перенесённые с [-1,1] на [a,b]:

        x_i = (a+b)/2 + (b-a)/2 * cos( (2i+1)/(2n+2) * pi ),  i = 0..n

    Такой набор узлов доставляет минимум величине max|omega(x)| среди всех
    наборов из n+1 точки. Узлы сгущаются к концам отрезка — туда, где
    равномерная сетка даёт выбросы.

    В тексте задания в знаменателе напечатано (2i+2) вместо (2n+2). Это
    опечатка: при (2i+2) аргумент косинуса равен (2i+1)pi/(2i+2) и растёт
    к pi, все узлы сползают в левую половину отрезка, а правый край не
    покрывается вовсе. Здесь используется каноническая формула.

    cos(...) убывает по i, поэтому узлы выходят в порядке убывания —
    сортируем, чтобы дальше искать участок бинарным поиском.
    """
    mid, half = (a + b) / 2.0, (b - a) / 2.0
    x = [mid + half * math.cos((2 * i + 1) * math.pi / (2 * n + 2))
         for i in range(n + 1)]
    x.sort()
    return x


# =============================================================================
#        ЗАДАЧА 1. ПОЛИНОМ ПО ВЫЧИСЛИТЕЛЬНОЙ СХЕМЕ ЭЙТКЕНА (вариант 2)
# =============================================================================
# Схема считает значение многочлена в точке, а не его коэффициенты, поэтому
# процедура принимает точку t сразу вместе с таблицей узлов. Разделения на
# «построение» и «вычисление», как у форм Лагранжа и Ньютона, здесь нет: для
# каждой новой точки таблица Эйткена заполняется заново.
# =============================================================================
def aitken_eval(x, f, t):
    """
    Значение P_n(t) по схеме Эйткена (формулы (6) и (7) пособия).

    Многочлен степени k, построенный по точкам с номерами от i-k до i,
    получается из двух многочленов степени k-1 по соседним наборам точек:

        L_{i-k..i}(t) =
            [ L_{i-k..i-1}(t) (x_i - t) - L_{i-k+1..i}(t) (x_{i-k} - t) ]
            / (x_i - x_{i-k})

    Проверка в узлах объясняет, почему это интерполяция. При t = x_i множитель
    (x_i - t) обращается в ноль, и от суммы остаётся только правый набор,
    делённый на (x_i - x_{i-k}) и умноженный на ту же разность; этот набор
    содержит узел x_i, поэтому по индукции даёт f_i. При t = x_{i-k}
    симметрично исчезает второе слагаемое и остаётся левый набор, содержащий
    x_{i-k}. Во внутреннем узле x_j оба набора дают f_j, а множители
    складываются в (x_i - x_j) - (x_{i-k} - x_j) = x_i - x_{i-k}, что
    сокращается со знаменателем.

    Таблица заполняется по строкам. Строка i — это список
    [ f_i, L_{i-1,i}, L_{i-2..i}, ..., L_{0..i} ], её k-й элемент строится из
    (k-1)-го элемента этой же строки и (k-1)-го элемента предыдущей. Значит,
    вся предыстория не нужна: достаточно держать одну строку, prev. Память
    O(n) вместо O(n^2) на полную таблицу.

    Последний элемент последней строки — L_{0..n}(t) = P_n(t).

    Трудоёмкость одного вычисления — n(n+1)/2 элементов таблицы, то есть
    O(n^2) действий на точку. Это дороже, чем у форм с коэффициентами, где
    O(n^2) тратится один раз на построение, а каждое последующее значение
    стоит O(n) по схеме Горнера. Схема Эйткена выгодна тогда, когда значение
    нужно в одной-двух точках, а не на всём отрезке.
    """
    n = len(x) - 1
    prev = [f[0]]                              # строка 0 состоит из одного f_0
    for i in range(1, n + 1):
        row = [f[i]]                           # строка начинается со значения в узле
        dxi = x[i] - t                         # общий множитель для всей строки
        for k in range(1, i + 1):
            dxk = x[i - k] - t
            # prev[k-1] — набор без правой точки x_i,
            # row[k-1]  — набор без левой точки x_{i-k}
            row.append((prev[k - 1] * dxi - row[k - 1] * dxk) / (x[i] - x[i - k]))
        prev = row
    return prev[-1]


def aitken_table(x, f, t):
    """
    Полная треугольная таблица схемы Эйткена — та же рекурсия, но с хранением
    всех строк. Нужна только для печати в разделе тестирования: по таблице
    видно, как значение выходит на многочлен всё более высокой степени.

    Возвращает список строк; row[i][k] — значение L_{i-k..i}(t).
    """
    tab = []
    for i in range(len(x)):
        row = [f[i]]
        for k in range(1, i + 1):
            row.append((tab[i - 1][k - 1] * (x[i] - t)
                        - row[k - 1] * (x[i - k] - t)) / (x[i] - x[i - k]))
        tab.append(row)
    return tab


# =============================================================================
#      ЗАДАЧА 2. КУБИЧЕСКИЙ СПЛАЙН, КРАЕВЫЕ УСЛОВИЯ S''(x0)=A, S''(xn)=B
# =============================================================================
def thomas(lower, main, upper, rhs):
    """
    Метод прогонки для трёхдиагональной СЛАУ A*y = rhs.

    Нумерация с нуля, N = len(main):
        lower[i] — элемент под главной диагональю в строке i (lower[0] не
                   используется);
        main[i]  — элемент главной диагонали в строке i;
        upper[i] — элемент над главной диагональю (upper[N-1] не
                   используется);
        rhs[i]   — правая часть строки i.

    Прогонка — это гауссово исключение, приспособленное к трёхдиагональной
    матрице. Решение ищется в виде рекуррентной связи соседних неизвестных

        y_i = M_i - L_i * y_{i+1}                                    (*)

    Прямой ход находит L_i и M_i. Первая строка,
    main[0]*y_0 + upper[0]*y_1 = rhs[0], сразу даёт

        L_0 = upper[0]/main[0],      M_0 = rhs[0]/main[0]

    Для строки i подставляем y_{i-1} из (*) в
    lower[i]*y_{i-1} + main[i]*y_i + upper[i]*y_{i+1} = rhs[i]
    и приводим к виду (*). Знаменатель общий для обоих коэффициентов:

        den = main[i] - lower[i]*L_{i-1}
        L_i = upper[i]/den
        M_i = (rhs[i] - lower[i]*M_{i-1})/den

    В последней строке наддиагонали нет, поэтому L_{N-1} = 0 и из (*) сразу
    y_{N-1} = M_{N-1}. Обратный ход идёт вверх по той же формуле (*).

    При диагональном преобладании (|main| > |lower| + |upper|) получается
    |L_i| < 1, знаменатель не обращается в ноль и прогонка устойчива. Для
    сплайновой системы преобладание есть: 2(h_i + h_{i+1}) > h_i + h_{i+1}.
    Стоит всё O(N) действий и O(N) памяти против O(N^3) у метода Гаусса для
    плотной матрицы.
    """
    N = len(main)
    L = [0.0] * N
    M = [0.0] * N

    # первая строка задаёт старт рекурсии
    if abs(main[0]) < 1e-300:
        raise ZeroDivisionError("Нулевой ведущий элемент в прогонке")
    L[0] = upper[0] / main[0]
    M[0] = rhs[0] / main[0]

    for i in range(1, N):
        den = main[i] - lower[i] * L[i - 1]
        if abs(den) < 1e-300:
            raise ZeroDivisionError("Нулевой знаменатель в прогонке")
        # в последней строке наддиагонали нет, поэтому L = 0
        L[i] = (upper[i] / den) if i < N - 1 else 0.0
        M[i] = (rhs[i] - lower[i] * M[i - 1]) / den

    y = [0.0] * N
    y[N - 1] = M[N - 1]
    for i in range(N - 2, -1, -1):
        y[i] = M[i] - L[i] * y[i + 1]
    return y


def spline_build(x, f, A, B):
    """
    Построение кубического сплайна в канонической форме.

    Возвращает четыре списка (a, b, c, d) длины n+1; значимые индексы 1..n,
    кроме c — у него используется и c[0], фиктивная переменная, равная
    S''(x_0) = A.

    Откуда берутся формулы. На участке [x_{i-1}, x_i] сплайн записан
    относительно правой границы:

        S_i(x)   = a_i + b_i(x-x_i) + c_i/2 (x-x_i)^2 + d_i/6 (x-x_i)^3
        S_i'(x)  = b_i + c_i(x-x_i) + d_i/2 (x-x_i)^2
        S_i''(x) = c_i + d_i(x-x_i)

    1) Подстановка x = x_i обнуляет все скобки:
           S_i(x_i) = a_i     =>  a_i = f_i
           S_i''(x_i) = c_i   =>  c_i есть вторая производная в узле x_i

    2) Подстановка x = x_{i-1} во вторую производную (скобка равна -h_i):
           S_i''(x_{i-1}) = c_i - d_i*h_i
       Это должно равняться c_{i-1} — второй производной в том же узле,
       посчитанной по соседнему участку. Отсюда d_i = (c_i - c_{i-1})/h_i.

    3) Подстановка x = x_{i-1} в сам сплайн при S_i(x_{i-1}) = f_{i-1}:
           a_i - b_i h_i + c_i/2 h_i^2 - d_i/6 h_i^3 = f_{i-1}
       Выражаем b_i и подставляем d_i из пункта 2:
           b_i = (f_i - f_{i-1})/h_i + (2c_i + c_{i-1}) h_i / 6

    Так все коэффициенты выражаются через набор c_i. Остаётся найти c_i.

    4) Не использовано ещё одно условие — непрерывность первой производной
       во внутренних узлах, S_i'(x_i) = S_{i+1}'(x_i). Слева это b_i,
       справа b_{i+1} - c_{i+1}h_{i+1} + d_{i+1}h_{i+1}^2/2. После
       подстановки выражений для b и d получается трёхдиагональная СЛАУ:

           h_i*c_{i-1} + 2(h_i + h_{i+1})*c_i + h_{i+1}*c_{i+1} =
                 6*( (f_{i+1}-f_i)/h_{i+1} - (f_i-f_{i-1})/h_i ),   i = 1..n-1

       Правая часть — разность наклонов соседних хорд, то есть дискретный
       аналог второй производной функции в узле x_i.

    5) Уравнений n-1, неизвестных n+1. Два недостающих даёт вариант 5:
           S''(x_0) = A  =>  c_0 = A
           S''(x_n) = B  =>  c_n = B
       Краевые условия этого типа оказываются самыми простыми: они прямо
       задают крайние неизвестные. Для условий на первую производную
       пришлось бы выводить отдельные уравнения, связывающие c_0 с c_1.

    В матрице первая и последняя строки содержат по одному элементу,
    внутренние — по три. Диагональное преобладание строгое, поэтому решение
    существует, единственно, а прогонка устойчива.
    """
    n = len(x) - 1

    # шаги сетки: h[i] — длина участка [x_{i-1}, x_i], нумерация с единицы
    h = [0.0] * (n + 1)
    for i in range(1, n + 1):
        h[i] = x[i] - x[i - 1]

    # ---------------- сборка трёхдиагональной СЛАУ для c_0..c_n ------------
    N = n + 1                       # число неизвестных
    lower = [0.0] * N
    main = [0.0] * N
    upper = [0.0] * N
    rhs = [0.0] * N

    # краевое условие слева: 1*c_0 = A
    main[0] = 1.0
    upper[0] = 0.0
    rhs[0] = A

    # непрерывность S' в узлах x_1..x_{n-1}
    for i in range(1, n):
        lower[i] = h[i]                                  # коэффициент при c_{i-1}
        main[i] = 2.0 * (h[i] + h[i + 1])                # коэффициент при c_i
        upper[i] = h[i + 1]                              # коэффициент при c_{i+1}
        # разность наклонов соседних хорд, умноженная на 6
        rhs[i] = 6.0 * ((f[i + 1] - f[i]) / h[i + 1] - (f[i] - f[i - 1]) / h[i])

    # краевое условие справа: 1*c_n = B
    lower[n] = 0.0
    main[n] = 1.0
    rhs[n] = B

    c = thomas(lower, main, upper, rhs)

    # остальные коэффициенты — по формулам из пунктов 1-3 docstring
    a = [0.0] * (n + 1)
    b = [0.0] * (n + 1)
    d = [0.0] * (n + 1)
    for i in range(1, n + 1):
        a[i] = f[i]                                      # значение в правом узле
        d[i] = (c[i] - c[i - 1]) / h[i]                  # третья производная
        b[i] = (f[i] - f[i - 1]) / h[i] + (2.0 * c[i] + c[i - 1]) * h[i] / 6.0
    return a, b, c, d


def spline_eval(x, a, b, c, d, t):
    """
    Значение сплайна S(t).

    Сначала ищется номер участка i, для которого t лежит в [x_{i-1}, x_i].
    Сетка отсортирована, поэтому поиск бинарный, O(log n) вместо O(n)
    перебором; ищется минимальный i с условием t <= x[i]. Точки левее x_0 и
    правее x_n считаются по крайним участкам — в наших экспериментах это
    только границы контрольной сетки.

    Дальше вычисляется многочлен участка с отсчётом от правой границы:
    dx = t - x_i, для внутренних точек участка отрицательно.
    """
    n = len(x) - 1

    i = 1
    if t <= x[0]:
        i = 1                                   # левее сетки — первый участок
    elif t >= x[n]:
        i = n                                   # правее сетки — последний
    else:
        lo, hi = 1, n
        while lo < hi:
            mid = (lo + hi) // 2
            if t <= x[mid]:
                hi = mid
            else:
                lo = mid + 1
        i = lo

    dx = t - x[i]
    return a[i] + b[i] * dx + c[i] / 2.0 * dx * dx + d[i] / 6.0 * dx ** 3


# =============================================================================
#                   ПОГРЕШНОСТЬ ИНТЕРПОЛЯЦИИ НА ОТРЕЗКЕ
# =============================================================================
def max_error(fun, approx, a, b, m=2001):
    """
    Максимум |f(x) - P(x)| по отрезку [a, b] — мера погрешности интерполяции.

    В узлах интерполяции погрешность равна нулю по построению: и многочлен,
    и сплайн проходят через табличные значения точно. Считать погрешность по
    узлам бессмысленно — всегда выйдет ноль. Максимум ищется по
    промежуточным точкам, как требует замечание 2 к заданию.

    Контрольная сетка из m = 2001 равноотстоящей точки заведомо гуще любой
    рабочей (максимум n = 256), и её точки в общем случае не совпадают с
    узлами интерполяции.

    Вторая компонента ответа — точка, где максимум достигнут; для
    равномерной сетки она почти всегда оказывается у концов отрезка.
    """
    worst, xw = 0.0, a
    for k in range(m):
        t = a + (b - a) * k / (m - 1)
        e = abs(fun(t) - approx(t))
        if e > worst:
            worst, xw = e, t
    return worst, xw


