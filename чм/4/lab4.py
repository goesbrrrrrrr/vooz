# Набор охватывает четыре разные ситуации:
#   exp, sin — гладкие функции, ожидается быстрая сходимость;
#   runge    — бесконечно дифференцируема на отрезке, но имеет полюсы в
#              комплексной плоскости в точках x = +-i/5, лежащие близко к
#              отрезку; из-за этого производные высоких порядков растут
#              быстрее, чем (n+1)!, и многочлен расходится;
#   abs      — нет даже первой производной в нуле, оценка остаточного члена
#              неприменима; худший случай.
# =============================================================================
FUNCS = {
    "exp":   (lambda t: math.exp(t),                 -1.0, 1.0, "f(x) = e^x"),
    "runge": (lambda t: 1.0 / (1.0 + 25.0 * t * t),  -1.0, 1.0, "f(x) = 1/(1+25x^2)"),
    "sin":   (lambda t: math.sin(t),                  0.0, math.pi, "f(x) = sin x"),
    "abs":   (lambda t: abs(t),                      -1.0, 1.0, "f(x) = |x|"),
}

# Вторые производные нужны для краевых условий сплайна: A = f''(a), B = f''(b).
# Точные значения исключают лишнюю погрешность у границ, так что таблицы меряют
# точность метода, а не качество угадывания краевых условий. У |x| вторая
# производная равна нулю всюду, кроме точки излома.
FUNCS_D2 = {
    "exp":   lambda t: math.exp(t),
    "runge": lambda t: (50.0 * (75.0 * t * t - 1.0)) / (1.0 + 25.0 * t * t) ** 3,
    "sin":   lambda t: -math.sin(t),
    "abs":   lambda t: 0.0,
}


def poly_test(t):
    """Тестовый многочлен 3-й степени: 2x^3 - 3x^2 + x - 5"""
    return 2 * t ** 3 - 3 * t ** 2 + t - 5


