def draw(key, n, tag):
    """
    Четыре панели для одной функции и одной степени n: сверху сама функция,
    многочлен и сплайн с выделенными узлами, снизу графики погрешности
    e(x) = f(x) - P(x); слева равномерные узлы, справа чебышёвские.

    Такая раскладка показывает на одном рисунке разницу между многочленом и
    сплайном (внутри панели), разницу между типами узлов (между столбцами) и
    структуру погрешности (нижний ряд).

    Ограничение по вертикали в верхнем ряду ставится по диапазону функции с
    запасом: иначе выбросы расходящегося многочлена на функции Рунге
    достигают десятков и сожмут график функции в линию.
    """
    fun, a, b, label = FUNCS[key]
    d2 = FUNCS_D2[key]
    # густая сетка для гладкой отрисовки кривых
    tt = [a + (b - a) * k / 800.0 for k in range(801)]
    ft_ = [fun(t) for t in tt]

    fig, ax = plt.subplots(2, 2, figsize=(14, 8))
    fig.suptitle("%s,  n = %d" % (label, n), fontsize=14)

    for col, nodes, nm in ((0, nodes_uniform, "равномерные узлы"),
                           (1, nodes_chebyshev, "узлы Чебышева")):
        xs = nodes(a, b, n)
        fs = [fun(t) for t in xs]
        pp = [aitken_eval(xs, fs, t) for t in tt]
        aa, bb2, cc, dd = spline_build(xs, fs, d2(xs[0]), d2(xs[-1]))
        ss = [spline_eval(xs, aa, bb2, cc, dd, t) for t in tt]

        ax[0][col].plot(tt, ft_, "k-", lw=2, label="f(x)")
        ax[0][col].plot(tt, pp, "r--", lw=1.4, label="P_n(x) (Эйткен)")
        ax[0][col].plot(tt, ss, "b-.", lw=1.4, label="S(x) (сплайн)")
        ax[0][col].plot(xs, fs, "go", ms=5, label="узлы интерполяции")
        lo, hi = min(ft_), max(ft_)
        pad = 0.6 * (hi - lo) + 0.1        # запас, чтобы выбросы не сжимали график
        ax[0][col].set_ylim(lo - pad, hi + pad)
        ax[0][col].set_title("Функция и приближения — %s" % nm)
        ax[0][col].legend(fontsize=8)
        ax[0][col].grid(True)

        # в узлах погрешности обязаны быть нулевыми
        ax[1][col].plot(tt, [ft_[i] - pp[i] for i in range(len(tt))],
                        "r-", lw=1.2, label="e(x) = f - P_n")
        ax[1][col].plot(tt, [ft_[i] - ss[i] for i in range(len(tt))],
                        "b-", lw=1.2, label="e(x) = f - S")
