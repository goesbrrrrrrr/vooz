    print("-" * 74)
    prev = None
    for n in SPLITS:
        row = []
        for nodes in (nodes_uniform, nodes_chebyshev):
            xs = nodes(a, b, n)
            fs = [fun(t) for t in xs]
            # краевые условия — точные значения второй производной на концах
