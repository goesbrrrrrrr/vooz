#             ПРАВЫЕ ЧАСТИ СИСТЕМЫ ПОСЛЕ СВЕДЕНИЯ К 1-МУ ПОРЯДКУ
# =============================================================================
def f1(x, y, z):
    """Правая часть первого уравнения системы: y' = z"""
    return z


def f2(x, y, z):
    """
    Правая часть второго уравнения системы: z' = 4z - 5y + 3x.

    Получена из y'' - 4y' + 5y = 3x переносом всего, кроме y'', вправо:
    y'' = 4y' - 5y + 3x, и с учётом z = y' это z' = 4z - 5y + 3x.
    """
    return 4 * z - 5 * y + 3 * x


# ========================= Точное решение задачи =============================
def y_exact(x):
    """
    Точное решение задачи Коши  y'' - 4y' + 5y = 3x,  y(0)=1.48,  y'(0)=3.6.

    1) Однородная часть. Характеристическое уравнение r^2 - 4r + 5 = 0,
       дискриминант 16 - 20 = -4, корни комплексно-сопряжённые r = 2 +- i:
           y_odn = e^(2x) * (C1*cos x + C2*sin x)

    2) Частное решение. Правая часть 3x — многочлен 1-й степени, и число 0
       не корень характеристического уравнения, поэтому частное решение
       ищем в том же виде y_p = A*x + B. Тогда y_p' = A, y_p'' = 0:
           0 - 4A + 5(Ax + B) = 3x
           5A*x + (5B - 4A) = 3x
       Приравнивая коэффициенты: 5A = 3 => A = 0.6;  5B = 4A => B = 0.48.

    3) Общее решение:
           y = e^(2x)*(C1*cos x + C2*sin x) + 0.6x + 0.48

    4) Начальные условия:
           y(0)  = C1 + 0.48 = 1.48          =>  C1 = 1
           y'(0) = 2*C1 + C2 + 0.6 = 3.6     =>  C2 = 1

    Ответ:  y(x) = e^(2x) * (cos x + sin x) + 0.6*x + 0.48

    Множитель e^(2x) означает экспоненциальный рост решения. Отсюда и резкий
    рост числа подотрезков с увеличением b при фиксированной абсолютной
    точности — см. раздел про правую границу.
    """
    return np.exp(2 * x) * (np.cos(x) + np.sin(x)) + 0.6 * x + 0.48


# ========================= Явный метод Эйлера ================================
def euler_method(x0, b, y0, z0, n):
    """
    Явный метод Эйлера для системы ОДУ. Порядок точности p = 1.

    Разложим решение в ряд Тейлора в точке x_i и оставим два члена:
    y(x_i + h) = y(x_i) + h*y'(x_i) + O(h^2). Производная y'(x_i) известна —
    это правая часть уравнения. Отбрасывая остаток, получаем формулы:

        y_{i+1} = y_i + h * f1(x_i, y_i, z_i)
        z_{i+1} = z_i + h * f2(x_i, y_i, z_i)

    В правые части подставляются значения с предыдущего слоя, y_i и z_i, а
    не уже пересчитанные. Поэтому счёт идёт во временные переменные y_new и
    z_new и только потом пишется в массивы: иначе при вычислении z_{i+1}
    использовалось бы новое y, и схема стала бы другим методом.

    Геометрически решение продолжается по касательной, проведённой в левом
    конце подотрезка. Для выпуклого растущего решения касательная идёт ниже
    кривой, поэтому метод систематически занижает значение.

    Шаг стоит одного вычисления каждой правой части. Локальная погрешность
    O(h^2), накопленная за n шагов O(h).
    """
    h = (b - x0) / n
    x = np.linspace(x0, b, n + 1)
    y = np.zeros(n + 1)
    z = np.zeros(n + 1)
    y[0] = y0                       # начальное условие для y
    z[0] = z0                       # начальное условие для z = y'

    for i in range(n):
        # обе компоненты считаются от одного и того же предыдущего слоя
        y_new = y[i] + h * f1(x[i], y[i], z[i])
        z_new = z[i] + h * f2(x[i], y[i], z[i])
        y[i + 1] = y_new
        z[i + 1] = z_new

    return x, y, z


# ====================== Метод Рунге-Кутта 3.1 ================================
def rk31_method(x0, b, y0, z0, n):
    """
    Метод типа Рунге-Кутта, формула 3.1 (вариант 26). Порядок точности p = 3.

    В записи пособия y_{n+1} = y_n + Delta_y_n:

        Delta_y_n = (1/6) * (k1 + 4*k2 + k3)
        k1 = h * f(x_n,       y_n)
        k2 = h * f(x_n + h/2, y_n + k1/2)
        k3 = h * f(x_n + h,   y_n - k1 + 2*k2)

    Первая цифра составного номера формулы означает порядок метода, вторая —
    номер формулы в группе, отсюда p = 3.

    Вместо одной касательной, как у Эйлера, берётся взвешенное среднее трёх
    пробных наклонов: в начале подотрезка (k1), в середине (k2) и в конце
    (k3). Веса 1/6, 4/6, 1/6 подобраны так, чтобы разложение численного
    решения в ряд Тейлора совпало с точным вплоть до члена h^3. Структура
    весов та же, что у формулы Симпсона: при f, не зависящей от y, метод в
    точности в неё вырождается.

    Аргумент k3 — это y_n - k1 + 2*k2, а не y_n + k2. Комбинация
    (-k1 + 2*k2) экстраполирует наклон на правый конец подотрезка по двум
    уже известным наклонам, и на ней держится третий порядок; более
    «естественная» замена порядок ломает.

    При переносе на систему коэффициенты вычисляются одновременно для обеих
    компонент, и в аргументы обеих правых частей идут согласованные
    промежуточные значения и y, и z:

        k2_y = h*f1(x + h/2, y + k1_y/2, z + k1_z/2)
        k2_z = h*f2(x + h/2, y + k1_y/2, z + k1_z/2)   <- те же аргументы

    Если продвигать компоненты по отдельности — сначала полностью y, потом
    полностью z — метод потеряет третий порядок и выродится в схему первого.

    Шаг стоит трёх вычислений каждой правой части, втрое дороже
    эйлеровского. За счёт третьего порядка шагов требуется на несколько
    порядков меньше, так что итоговый выигрыш всё равно большой.
    """
    h = (b - x0) / n
    x = np.linspace(x0, b, n + 1)
    y = np.zeros(n + 1)
    z = np.zeros(n + 1)
    y[0] = y0
    z[0] = z0

    for i in range(n):
        # k1 — наклон в левом конце подотрезка
        k1_y = h * f1(x[i], y[i], z[i])
        k1_z = h * f2(x[i], y[i], z[i])

        # k2 — наклон в середине, аргументы сдвинуты на половину k1
        k2_y = h * f1(x[i] + h / 2, y[i] + k1_y / 2, z[i] + k1_z / 2)
        k2_z = h * f2(x[i] + h / 2, y[i] + k1_y / 2, z[i] + k1_z / 2)

        # k3 — наклон в правом конце; аргумент (-k1 + 2*k2) экстраполирует
        # наклон по двум предыдущим
        k3_y = h * f1(x[i] + h, y[i] - k1_y + 2 * k2_y, z[i] - k1_z + 2 * k2_z)
        k3_z = h * f2(x[i] + h, y[i] - k1_y + 2 * k2_y, z[i] - k1_z + 2 * k2_z)

        # взвешенное среднее трёх наклонов с весами 1 : 4 : 1
        y[i + 1] = y[i] + (k1_y + 4 * k2_y + k3_y) / 6
        z[i + 1] = z[i] + (k1_z + 4 * k2_z + k3_z) / 6

    return x, y, z


# ====================== Правило Рунге ========================================
def runge_error(y_n, y_2n, p):
    """
    Апостериорная оценка погрешности по правилу Рунге:

        delta(n, 2n) = |y_n - y_2n| / (2^p - 1)

    Пусть y* — точное значение, а метод имеет порядок p. Тогда для
    достаточно мелкой сетки погрешность ведёт себя как C*h^p:

        y_n  = y* + C*h^p               (сетка из n подотрезков, шаг h)
        y_2n = y* + C*(h/2)^p           (сетка из 2n подотрезков, шаг h/2)

    Вычтем второе из первого:

        y_n - y_2n = C*h^p * (1 - 1/2^p) = C*h^p * (2^p - 1)/2^p

    Отсюда погрешность более точного решения y_2n:

        y_2n - y* = C*(h/2)^p = C*h^p/2^p = (y_n - y_2n)/(2^p - 1)

    Разность двух численных решений, делённая на (2^p - 1), и есть оценка
    погрешности решения на более мелкой сетке. Неизвестная константа C при
    этом сокращается.

    Формула опирается на знание порядка p: при неверном p оценка окажется
    систематически завышена или занижена. Поэтому в конце программы порядок
    проверяется экспериментально.
    """
    return abs(y_n - y_2n) / (2**p - 1)


# ====================== Основной алгоритм ====================================
def solve_with_accuracy(method, x0, b, y0, z0, eps, p, n0=2):
    """
    Итерационное измельчение сетки до достижения заданной точности eps.

    1) Взять стартовое число подотрезков n = n0, посчитать решение.
    2) Удвоить сетку: n2 = 2n, посчитать решение на ней.
    3) Оценить погрешность по правилу Рунге, сравнив значения в крайнем
       правом узле обоих решений (индекс -1).
    4) Если delta <= eps — остановиться, ответ есть решение на сетке 2n, оно
       точнее. Иначе решение на 2n становится предыдущим и возвращаемся к
       пункту 2.

    Каждая итерация переиспользует решение с предыдущего круга
    (y_prev = y_curr), поэтому на итерацию приходится один новый расчёт, а
    не два.

    Если требуемая точность недостижима — например, метод Эйлера при малом
    eps на длинном отрезке — цикл был бы бесконечным, и его обрывает
    ограничение n <= 2^20. В этом случае возвращается флаг ok = False:
    результат помечается как не достигший точности, иначе в таблице он
    выглядел бы так же, как честно сошедшийся.

    Возвращает:
        n_final — количество подотрезков при достигнутой точности
        y_b     — значение y(b)
        x_first, y_first — сетка и решение при n0 (начальное, для графика)
        x_last, y_last   — сетка и решение при n_final (финальное, для графика)
        delta   — последняя оценка погрешности по правилу Рунге
        ok      — True, если требуемая точность достигнута
    """
    n = n0
    x_prev, y_prev, z_prev = method(x0, b, y0, z0, n)
    # стартовая сетка нужна для графической интерпретации
    x_first, y_first = x_prev.copy(), y_prev.copy()

    while True:
        n2 = 2 * n
        x_curr, y_curr, z_curr = method(x0, b, y0, z0, n2)
        # сравниваются значения в крайнем правом узле обеих сеток
        delta = runge_error(y_prev[-1], y_curr[-1], p)
        if delta <= eps:
            return n2, y_curr[-1], x_first, y_first, x_curr, y_curr, delta, True
        # точность не достигнута: текущее решение становится предыдущим,
        # лишнего пересчёта не происходит
        n = n2
        x_prev, y_prev, z_prev = x_curr, y_curr, z_curr
        # защита от бесконечного цикла: точность не достигнута
        if n > 2**20:
            return n, y_curr[-1], x_first, y_first, x_curr, y_curr, delta, False


# ====================== Параметры задачи =====================================
x0 = 0.0
y0 = 1.48
z0 = 3.6  # y'(0)

# Правая граница (можно менять для исследования)
b_values = [1.0, 2.0]
eps_values = [0.01, 0.001, 0.0001, 0.00001]
