# =============================================================================
for b in b_values:
    print("=" * 80)
    print(f"  Интервал интегрирования: [{x0}, {b}]")
    print("=" * 80)
    yb_exact = y_exact(b)
    print(f"  Точное решение: y({b}) = {yb_exact:.10f}")
    print()
    print(f"{'ε₀':>10} | {'n (Эйлер)':>10} | {'n (РК 3.1)':>10} | "
          f"{'y(b) Эйлер':>14} | {'y(b) РК 3.1':>14} | "
          f"{'|Δ| Эйлер':>11} | {'|Δ| РК 3.1':>11}")
    print("-" * 104)

    for eps in eps_values:
        # Явный метод Эйлера
        n_e, yb_e, xf_e, yf_e, xl_e, yl_e, d_e, ok_e = solve_with_accuracy(
            euler_method, x0, b, y0, z0, eps, p_euler, n0
        )
        # Метод Рунге-Кутта 3.1
        n_rk, yb_rk, xf_rk, yf_rk, xl_rk, yl_rk, d_rk, ok_rk = solve_with_accuracy(
            rk31_method, x0, b, y0, z0, eps, p_rk31, n0
        )

        # фактическая погрешность относительно точного решения
        er_e = abs(yb_exact - yb_e)
        er_rk = abs(yb_exact - yb_rk)

        # если точность не достигнута — вместо числа подотрезков метка,
        # чтобы строка не выглядела как успешная
        ne = f"{n_e:>10d}" if ok_e else f"{'>2^20':>10}"
        nr = f"{n_rk:>10d}" if ok_rk else f"{'>2^20':>10}"
        print(f"{eps:>10.5f} | {ne} | {nr} | "
              f"{yb_e:>14.8f} | {yb_rk:>14.8f} | "
              f"{er_e:>11.3e} | {er_rk:>11.3e}")

    print("  '>2^20' — требуемая точность не достигнута за 2^20 подотрезков.")
    print()

