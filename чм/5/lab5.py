    axes[0].set_xlabel("x")
    axes[0].set_ylabel("y")
    axes[0].legend()
    axes[0].grid(True)

    # --- Метод Рунге-Кутта 3.1 ---
    n_rk, yb_rk, xf_rk, yf_rk, xl_rk, yl_rk, d_rk, ok_rk = solve_with_accuracy(
        rk31_method, x0, b, y0, z0, eps, p_rk31, n0
    )
    axes[1].plot(x_fine, y_fine, 'k--', lw=2.0, zorder=5, label="точное решение")
    axes[1].plot(xf_rk, yf_rk, 'ro-', markersize=4, label=f"n₀ = {n0} (начальная сетка)")
    axes[1].plot(xl_rk, yl_rk, 'b.-', markersize=2, label=f"n = {n_rk} (финальная сетка)")
    axes[1].set_title(f"Метод Рунге-Кутта 3.1\ny({b}) = {yb_rk:.8f}, n = {n_rk}")
    axes[1].set_xlabel("x")
    axes[1].set_ylabel("y")
    axes[1].legend()
