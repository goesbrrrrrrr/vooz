# =============================================================================
# Проверка порядка точности
# =============================================================================
# Если метод имеет порядок p, то погрешность пропорциональна h^p. При
# удвоении числа подотрезков шаг уменьшается вдвое, значит погрешность
# должна уменьшиться примерно в 2^p раз. Считаем отношение погрешностей на
# соседних сетках и смотрим, к чему оно стремится: для Эйлера (p=1) к 2,
# для РК 3.1 (p=3) к 8.
#
# Проверка идёт двумя независимыми способами: по разности решений на
# соседних сетках delta(n,2n), которую можно считать и без точного решения,
# и по истинной погрешности |y - y*|. Совпадение столбцов подтверждает, что
# правило Рунге годится как критерий остановки.
# =============================================================================
print("\n" + "=" * 80)
print("  Проверка порядка точности методов")
print("=" * 80)
b = 1.0

yb_exact = y_exact(b)
print(f"Точное решение: y({b}) = {yb_exact:.12f}")

for name, method, kmax, p in (("Явный метод Эйлера", euler_method, 12, 1),
                              ("Метод Рунге-Кутта 3.1", rk31_method, 10, 3)):
    print(f"\n{name} (ожидаемый порядок p = {p}, отношения → {2**p}):")
    print(f"{'n':>8} | {'y(b)':>16} | {'δ(n,2n)':>12} | {'отн. δ':>8} | "
          f"{'|y-y*|':>12} | {'отн. ошибки':>11}")
    print("-" * 82)
    prev_delta = prev_err = None
    for k in range(2, kmax):
        n = 2**k
        # два решения на соседних сетках: из n и из 2n подотрезков
        _, y_n, _ = method(x0, b, y0, z0, n)
        _, y_2n, _ = method(x0, b, y0, z0, 2 * n)
        # берётся разность без деления на (2^p - 1): для отношения соседних
        # величин общий множитель не важен
        delta = abs(y_n[-1] - y_2n[-1])
        err = abs(yb_exact - y_n[-1])
        # на первой строке сравнивать не с чем
        r_d = prev_delta / delta if prev_delta else float('nan')
        r_e = prev_err / err if prev_err else float('nan')
        print(f"{n:>8d} | {y_n[-1]:>16.10f} | {delta:>12.2e} | {r_d:>8.3f} | "
              f"{err:>12.2e} | {r_e:>11.3f}")
        prev_delta, prev_err = delta, err

print("\nПримечание: отношение δ должно стремиться к 2^p")
print("  Для Эйлера (p=1): отношение → 2")
print("  Для РК 3.1 (p=3): отношение → 8")
