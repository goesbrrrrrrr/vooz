h1(doc, "3. Теоретические сведения")

h2(doc, "3.1. Интерполяционный многочлен в форме Ньютона")
para(doc, "Интерполяционный многочлен в форме Ньютона записывается как")
formula(doc, "Pₙ(x) = b₀ + b₁(x − x₀) + b₂(x − x₀)(x − x₁) + … + "
             "bₙ(x − x₀)(x − x₁)…(x − xₙ₋₁).")
para(doc, "Главное вычислительное достоинство этой формы состоит в том, что "
          "коэффициенты bₖ не зависят от степени строящегося многочлена: при "
          "добавлении нового узла ранее вычисленные коэффициенты сохраняются, "
          "и многочлен достраивается одним слагаемым. Значение многочлена в "
          "точке вычисляется по обобщённой схеме Горнера за O(n) действий:")
formula(doc, "Pₙ(x) = b₀ + (x − x₀)(b₁ + (x − x₁)(b₂ + … ))")

h2(doc, "3.2. Коэффициенты bₖ по явным формулам (вариант 5)")
para(doc, "Согласно индивидуальному варианту коэффициенты bₖ вычисляются не по "
          "таблице разделённых разностей, а по явным замкнутым формулам "
          "(формула (27) пособия):")
formula(doc, "b₀ = f₀,")
formula(doc, "b₁ = f₀/(x₀ − x₁) + f₁/(x₁ − x₀),")
formula(doc, "b₂ = f₀/((x₀−x₁)(x₀−x₂)) + f₁/((x₁−x₀)(x₁−x₂)) + f₂/((x₂−x₀)(x₂−x₁)),")
para(doc, "и в общем случае")
formula(doc, "bₖ = Σ (j = 0..k)  fⱼ / Π (m = 0..k, m ≠ j) (xⱼ − xₘ).")
para(doc, "Каждый коэффициент вычисляется независимо от остальных, по своей "
          "формуле; рекуррентная таблица разностей не строится. Это делает "
          "схему удобной для параллельного вычисления и наглядно показывает "
          "структуру коэффициента, но повышает трудоёмкость: построение всех "
          "коэффициентов требует O(n³) операций против O(n²) для схемы с "
          "таблицей разделённых разностей. Для значений n, используемых в "
          "работе (до 40), это не является ограничением.")
para(doc, "Для равноотстоящих узлов xᵢ = x₀ + ih формула упрощается до")
formula(doc, "bₖ = Σ (i = 0..k) (−1)^(k−i) · fᵢ / (i!·(k−i)!·hᵏ).")

h2(doc, "3.3. Выбор узлов интерполяции")
para(doc, "В работе используются два способа разбиения отрезка [a, b].")
para(doc, "Равномерное разбиение:")
formula(doc, "xᵢ = a + (b − a)/n · i,   i = 0, 1, …, n.")
para(doc, "Разбиение Чебышёва (узлы — нули многочлена Чебышёва первого рода, "
          "перенесённые на отрезок [a, b]):")
formula(doc, "xᵢ = (a + b)/2 + (b − a)/2 · cos( (2i + 1)π / (2n + 2) ),   i = 0, 1, …, n.")
para(doc, "Примечание. В тексте задания в знаменателе аргумента косинуса "
          "напечатано (2i + 2) вместо (2n + 2). Это опечатка: при (2i + 2) "
          "аргумент косинуса равен (2i+1)π/(2i+2) и монотонно стремится к π, "
          "поэтому все узлы сползают в левую половину отрезка и правая его "
          "часть вообще не покрывается узлами. В работе используется "
          "каноническая формула чебышёвских узлов, приведённая выше.")
para(doc, "Смысл чебышёвского разбиения состоит в том, что именно такой выбор "
          "узлов минимизирует максимум модуля произведения "
          "ω(x) = (x − x₀)…(x − xₙ) на отрезке [a, b]. Узлы при этом сгущаются "
          "к концам отрезка, что подавляет характерные для равномерной сетки "
          "выбросы погрешности вблизи границ.")

h2(doc, "3.4. Остаточный член интерполирования")
para(doc, "Разность между интерполируемой функцией и её интерполяционным "
          "многочленом называют остаточным членом интерполирования: "
          "Rₙ(f, x) = f(x) − Pₙ(x). Если f(x) непрерывно дифференцируема "
          "(n + 1) раз на отрезке [a, b], содержащем узлы интерполирования, то "
          "для любой точки x ∈ [a, b] существует такая точка ξ ∈ [a, b], что")
formula(doc, "Rₙ(f, x) = f⁽ⁿ⁺¹⁾(ξ)/(n + 1)! · Π (i = 0..n) (x − xᵢ).")
para(doc, "Остаточный член не зависит от формы записи многочлена, поэтому эта "
          "оценка одинаково справедлива и для формы Лагранжа, и для формы "
          "Ньютона. Из неё следует, что сходимость интерполяционного процесса "
          "при n → ∞ определяется соотношением между ростом f⁽ⁿ⁺¹⁾ и убыванием "
          "(n + 1)!.")

h2(doc, "3.5. Кубический сплайн: каноническая запись")
para(doc, "Кубический сплайн S(x) — функция, которая на каждом участке "
          "[xᵢ₋₁, xᵢ] задаётся многочленом степени не выше третьей, проходит "
          "через все табличные значения и дважды непрерывно дифференцируема на "
          "всём отрезке. Используется каноническая запись, в которой опорной "
          "точкой участка служит его правая граница xᵢ:")
formula(doc, "Sᵢ(x) = aᵢ + bᵢ(x − xᵢ) + cᵢ/2·(x − xᵢ)² + dᵢ/6·(x − xᵢ)³,")
formula(doc, "x ∈ [xᵢ₋₁, xᵢ],   i = 1, …, n,   hᵢ = xᵢ − xᵢ₋₁.")
para(doc, "Условия сопряжения во внутренних узлах требуют совпадения значений "
          "самой функции, её первой и второй производных, вычисленных по "
          "формулам соседних участков Sᵢ(x) и Sᵢ₊₁(x).")
para(doc, "Из условия интерполяции в правом конце участка и из вида второй "
          "производной S″ᵢ(x) = cᵢ + dᵢ(x − xᵢ) сразу получаются выражения "
          "«младших» коэффициентов через cᵢ:")
formula(doc, "aᵢ = fᵢ,")
formula(doc, "dᵢ = (cᵢ − cᵢ₋₁)/hᵢ,")
formula(doc, "bᵢ = (fᵢ − fᵢ₋₁)/hᵢ + (2cᵢ + cᵢ₋₁)·hᵢ/6.")
para(doc, "Таким образом, все коэффициенты сплайна выражаются через набор "
          "величин cᵢ, имеющих смысл значений второй производной сплайна в "
          "узлах сетки.")

h2(doc, "3.6. СЛАУ для коэффициентов cᵢ и краевые условия варианта")
para(doc, "Условие непрерывности первой производной во внутренних узлах "
          "xᵢ (i = 1, …, n − 1) приводит к системе линейных уравнений "
          "относительно cᵢ:")
formula(doc, "hᵢ·cᵢ₋₁ + 2(hᵢ + hᵢ₊₁)·cᵢ + hᵢ₊₁·cᵢ₊₁ = "
             "6·[ (fᵢ₊₁ − fᵢ)/hᵢ₊₁ − (fᵢ − fᵢ₋₁)/hᵢ ].")
para(doc, "Это n − 1 уравнение относительно n + 1 неизвестной c₀, c₁, …, cₙ; "
          "недостающие два уравнения дают краевые условия. Согласно варианту 5 "
          "заданы значения второй производной на обоих концах отрезка: "
          "S″(x₀) = A, S″(xₙ) = B. Поскольку S″(x₀) = c₀ (фиктивная переменная, "
          "отвечающая левой границе первого участка) и S″(xₙ) = cₙ, краевые "
          "условия записываются предельно просто:")
formula(doc, "c₀ = A,      cₙ = B.")
para(doc, "Матрица получившейся системы трёхдиагональная: первая и последняя "
          "строки содержат по одному элементу, все остальные — по три. Во "
          "внутренних строках выполнено строгое диагональное преобладание, так "
          "как все шаги сетки положительны и "
          "2(hᵢ + hᵢ₊₁) > hᵢ + hᵢ₊₁. Это гарантирует однозначную разрешимость "
          "системы и устойчивость метода прогонки.")
para(doc, "Частный случай A = B = 0 даёт так называемый естественный сплайн. "
          "В настоящей работе, если вторая производная интерполируемой функции "
          "известна, краевые условия берутся точными: A = f″(a), B = f″(b) — "
          "это исключает дополнительную погрешность у границ отрезка.")

h2(doc, "3.7. Метод прогонки")
para(doc, "Трёхдиагональная система решается методом прогонки — тем же "
          "алгоритмом, что был реализован в лабораторной работе № 1. Прямой ход "
          "вычисляет прогоночные коэффициенты")
formula(doc, "L₁ = c₁ᵘᵖ/m₁,   M₁ = r₁/m₁,")
formula(doc, "Lᵢ = cᵢᵘᵖ/(mᵢ − lᵢ·Lᵢ₋₁),   Mᵢ = (rᵢ − lᵢ·Mᵢ₋₁)/(mᵢ − lᵢ·Lᵢ₋₁),")
para(doc, "где lᵢ, mᵢ, cᵢᵘᵖ — элементы поддиагонали, главной диагонали и "
          "наддиагонали, rᵢ — правая часть. Обратный ход даёт решение:")
formula(doc, "yₙ = Mₙ,   yᵢ = Mᵢ − Lᵢ·yᵢ₊₁.")
para(doc, "Трудоёмкость метода — O(n) арифметических действий и O(n) памяти, "
          "что делает построение сплайна практически столь же дешёвым, как и "
          "вычисление коэффициентов многочлена.")

h2(doc, "3.8. Мера погрешности интерполяции")
para(doc, "Мерой погрешности служит максимальное по модулю значение "
          "погрешности интерполяции на отрезке:")
formula(doc, "‖e‖ = max |f(x) − P(x)|,   x ∈ [a, b].")
para(doc, "В узлах интерполяции погрешность равна нулю по построению, поэтому, "
          "согласно замечанию к заданию, максимум ищется по промежуточным "
          "между узлами точкам. В программе используется густая контрольная "
          "сетка из 2001 равноотстоящей точки, не совпадающая с узлами "
          "интерполяции.")
page_break(doc)

