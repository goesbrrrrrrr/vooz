formula(doc, "k₂ʸ = h·f₁(xᵢ + h/2, yᵢ + k₁ʸ/2, zᵢ + k₁ᶻ/2),   k₂ᶻ — аналогично,")
formula(doc, "k₃ʸ = h·f₁(xᵢ + h, yᵢ − k₁ʸ + 2k₂ʸ, zᵢ − k₁ᶻ + 2k₂ᶻ),   k₃ᶻ — аналогично.")

h2(doc, "3.4. Правило Рунге и алгоритм удвоения сетки")
para(doc, "Точное решение при вычислительном эксперименте считается неизвестным, "
          "поэтому погрешность оценивается апостериорно. Пусть yₙ — численное "
          "решение в крайнем правом узле на сетке из n подотрезков, y₂ₙ — на "
          "сетке из 2n подотрезков, p — порядок точности метода. Тогда оценка "
          "погрешности по правилу Рунге:")
formula(doc, "δ(n, 2n) = |y₂ₙ − yₙ| / (2^p − 1).")
para(doc, "Алгоритм достижения заданной точности ε₀: начиная со стартового "
          "числа подотрезков n₀, сетка последовательно удваивается, и на каждой "
          "итерации вычисляется δ(n, 2n). Процесс останавливается, как только "
          "δ(n, 2n) ≤ ε₀; ответом считается решение на более мелкой из двух "
          "сеток. Для защиты от зацикливания введено ограничение n ≤ 2²⁰; если "
          "оно достигнуто, точность считается недостигнутой, и это явно "
          "отмечается в таблице результатов.")

